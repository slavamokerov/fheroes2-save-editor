#pragma once

#include <QImage>
#include <QPainter>
#include <QString>
#include <QStringList>

namespace fh2 {

class Assets;

// The game font: glyphs from FONT.ICN/SMALFONT.ICN + generation of CP1251 letters
// from Latin ones (port of generateCP1251Alphabet from fheroes2
// src/fheroes2/gui/ui_font.cpp). Shadows and the yellow palette — like in the engine.
class GameFont
{
public:
    enum class Size { SMALL, NORMAL };
    enum class Color { WHITE, YELLOW, GRAY, GREEN };

    explicit GameFont( const Assets * assets );

    bool valid() const { return _valid; }

    int textWidth( const QString & text, Size size ) const;
    int lineHeight( Size size ) const; // SMALL=11, NORMAL=17 (like in fheroes2)
    // The button font is a separate module buttonfont.h (in the game it is also
    // generated by code rather than taken from FONT.ICN).

    // Draws a single line. x,y — position of the line's top edge (like in fheroes2).
    void drawText( QPainter & p, int x, int y, const QString & text, Size size, Color color, int maxWidth = -1 ) const;

    // Multiline text: wraps by words within maxWidth, each line is
    // centered (port of fheroes2::Text::draw( x, y, maxWidth, output )).
    // '\n' in the text is a hard line break. Returns the number of drawn lines.
    int drawTextWrapped( QPainter & p, int x, int y, int maxWidth, const QString & text, Size size, Color color ) const;

    // Number of lines the text will occupy when wrapped to maxWidth (Text::rows).
    int textRows( const QString & text, Size size, int maxWidth ) const;

    // Truncates text to maxWidth with an ellipsis (game glyphs).
    QString elideText( const QString & text, Size size, int maxWidth ) const;

    struct Glyph {
        QImage img; // letter + shadow (like in fheroes2 — one buffer with a transform layer)
        QImage idx; // palette color indices (0xFF — transparent), for recoloring
        int x = 0;  // hotspot
        int y = 0;
        bool empty = true;
    };

    Glyph glyph( Size size, unsigned char code ) const;
    void drawGlyph( QPainter & p, int x, int y, const Glyph & g, Color color ) const;
    static void drawLetter( QPainter & p, int x, int y, const QImage & img, Color color );

private:
    QStringList wrapLines( const QString & text, Size size, int maxWidth ) const;

public:
    const Assets * _assets = nullptr;
    bool _valid = false;
    Glyph _normal[256];
    Glyph _small[256];
};

} // namespace fh2
