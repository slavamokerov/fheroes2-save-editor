// Legacy code page -> Unicode tables for gettext .mo msgstrs (generated).
// fheroes2 ships translations in single-byte encodings (CP1251 for Russian,
// CP1250 for Polish, CP1252 for Western languages, etc. — declared in the
// .mo header). These tables decode the high half (0x80..0xFF) to Unicode.
// cp1251ToUtf8-style usage: code points >= 0x800 need a 3-byte UTF-8 sequence.

namespace fh2 {
namespace codepages {

struct CodepageTable {
    const char * charset;
    const uint16_t * high; // 128 entries for bytes 0x80..0xFF
};

inline const CodepageTable * tableForCharset( const char * charset );

} // namespace codepages
} // namespace fh2

