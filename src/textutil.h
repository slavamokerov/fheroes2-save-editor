// Horizontal mirror for Qt versions both before and after the flipped() API
// (flipped() is only available in recent Qt; mirrored() is deprecated there).
inline QImage mirrorHorizontal( const QImage & img )
{
#if QT_VERSION >= QT_VERSION_CHECK( 6, 9, 0 )
    return img.flipped( Qt::Horizontal );
#else
    return img.mirrored( true, false );
#endif
}

// Replaces Latin-1 accented letters with plain ASCII ones. The game fonts
// only contain glyphs for the code page of the installed game resources
// (e.g. an English FONT.ICN has no umlauts) — the engine renders such texts
// with ASCII equivalents too. Used only for rendering, never for saving.
inline QString transliterateLatin1( const QString & s )
{
    static const QChar from[] = { QChar( 0x00C0 ), QChar( 0x00C1 ), QChar( 0x00C2 ), QChar( 0x00C3 ), QChar( 0x00C4 ), QChar( 0x00C5 ),
                                  QChar( 0x00C7 ), QChar( 0x00C8 ), QChar( 0x00C9 ), QChar( 0x00CA ), QChar( 0x00CB ), QChar( 0x00CC ),
                                  QChar( 0x00CD ), QChar( 0x00CE ), QChar( 0x00CF ), QChar( 0x00D1 ), QChar( 0x00D2 ), QChar( 0x00D3 ),
                                  QChar( 0x00D4 ), QChar( 0x00D5 ), QChar( 0x00D6 ), QChar( 0x00D9 ), QChar( 0x00DA ), QChar( 0x00DB ),
                                  QChar( 0x00DC ), QChar( 0x00DD ), QChar( 0x00E0 ), QChar( 0x00E1 ), QChar( 0x00E2 ), QChar( 0x00E3 ),
                                  QChar( 0x00E4 ), QChar( 0x00E5 ), QChar( 0x00E7 ), QChar( 0x00E8 ), QChar( 0x00E9 ), QChar( 0x00EA ),
                                  QChar( 0x00EB ), QChar( 0x00EC ), QChar( 0x00ED ), QChar( 0x00EE ), QChar( 0x00EF ), QChar( 0x00F1 ),
                                  QChar( 0x00F2 ), QChar( 0x00F3 ), QChar( 0x00F4 ), QChar( 0x00F5 ), QChar( 0x00F6 ), QChar( 0x00F9 ),
                                  QChar( 0x00FA ), QChar( 0x00FB ), QChar( 0x00FC ), QChar( 0x00FD ), QChar( 0x00FF ), QChar( 0x00DF ) };
    static const char to[] = { 'A', 'A', 'A', 'A', 'A', 'A', 'C', 'E', 'E', 'E', 'E', 'I', 'I', 'I', 'I', 'N', 'O', 'O',
                               'O', 'O', 'O', 'U', 'U', 'U', 'U', 'Y', 'a', 'a', 'a', 'a', 'a', 'a', 'c', 'e', 'e', 'e',
                               'e', 'i', 'i', 'i', 'i', 'n', 'o', 'o', 'o', 'o', 'o', 'u', 'u', 'u', 'u', 'y', 'y', 's' };
    QString out = s;
    for ( int i = 0; i < static_cast<int>( sizeof( from ) / sizeof( from[0] ) ); ++i )
        out.replace( from[i], QChar::fromLatin1( to[i] ) );
    return out;
}

// Decodes a cp1251 string (hero names in fheroes2 saves) into a QString.
inline QString decodeCp1251( const std::string & s )
{
    static const wchar_t table[128] = {
        0x0402, 0x0403, 0x201A, 0x0453, 0x201E, 0x2026, 0x2020, 0x2021, 0x20AC, 0x2030, 0x0409, 0x2039, 0x040A, 0x040C, 0x040B, 0x040F,
        0x0452, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014, 0x2122, 0x0459, 0x203A, 0x045A, 0x045C, 0x045B, 0x045F, 0x00A0,
        0x040E, 0x045E, 0x0408, 0x00A4, 0x0490, 0x00A6, 0x00A7, 0x0401, 0x00A9, 0x0404, 0x00AB, 0x00AC, 0x00AD, 0x00AE, 0x0407, 0x00B0,
        0x00B1, 0x0406, 0x0456, 0x0491, 0x00B5, 0x00B6, 0x00B7, 0x0451, 0x2116, 0x0454, 0x00BB, 0x0458, 0x0405, 0x0455, 0x0457, 0x00BF,
        0x0410, 0x0411, 0x0412, 0x0413, 0x0414, 0x0415, 0x0416, 0x0417, 0x0418, 0x0419, 0x041A, 0x041B, 0x041C, 0x041D, 0x041E, 0x041F,
        0x0420, 0x0421, 0x0422, 0x0423, 0x0424, 0x0425, 0x0426, 0x0427, 0x0428, 0x0429, 0x042A, 0x042B, 0x042C, 0x042D, 0x042E, 0x042F,
        0x0430, 0x0431, 0x0432, 0x0433, 0x0434, 0x0435, 0x0436, 0x0437, 0x0438, 0x0439, 0x043A, 0x043B, 0x043C, 0x043D, 0x043E, 0x043F,
        0x0440, 0x0441, 0x0442, 0x0443, 0x0444, 0x0445, 0x0446, 0x0447, 0x0448, 0x0449, 0x044A, 0x044B, 0x044C, 0x044D, 0x044E, 0x044F,
    };
    QString out;
    out.reserve( static_cast<int>( s.size() ) );
    for ( unsigned char c : s ) {
        if ( c < 0x80 )
            out.append( QChar( c ) );
        else
            out.append( QChar( table[c - 0x80] ) );
    }
    return out;
}

// Encodes a QString into cp1251 (the reverse of decodeCp1251).
// Characters without a cp1251 equivalent are replaced with '?'.
inline std::string encodeCp1251( const QString & s )
{
    static const wchar_t table[128] = {
        0x0402, 0x0403, 0x201A, 0x0453, 0x201E, 0x2026, 0x2020, 0x2021, 0x20AC, 0x2030, 0x0409, 0x2039, 0x040A, 0x040C, 0x040B, 0x040F,
        0x0452, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014, 0x2122, 0x0459, 0x203A, 0x045A, 0x045C, 0x045B, 0x045F, 0x00A0,
        0x040E, 0x045E, 0x0408, 0x00A4, 0x0490, 0x00A6, 0x00A7, 0x0401, 0x00A9, 0x0404, 0x00AB, 0x00AC, 0x00AD, 0x00AE, 0x0407, 0x00B0,
        0x00B1, 0x0406, 0x0456, 0x0491, 0x00B5, 0x00B6, 0x00B7, 0x0451, 0x2116, 0x0454, 0x00BB, 0x0458, 0x0405, 0x0455, 0x0457, 0x00BF,
        0x0410, 0x0411, 0x0412, 0x0413, 0x0414, 0x0415, 0x0416, 0x0417, 0x0418, 0x0419, 0x041A, 0x041B, 0x041C, 0x041D, 0x041E, 0x041F,
        0x0420, 0x0421, 0x0422, 0x0423, 0x0424, 0x0425, 0x0426, 0x0427, 0x0428, 0x0429, 0x042A, 0x042B, 0x042C, 0x042D, 0x042E, 0x042F,
        0x0430, 0x0431, 0x0432, 0x0433, 0x0434, 0x0435, 0x0436, 0x0437, 0x0438, 0x0439, 0x043A, 0x043B, 0x043C, 0x043D, 0x043E, 0x043F,
        0x0440, 0x0441, 0x0442, 0x0443, 0x0444, 0x0445, 0x0446, 0x0447, 0x0448, 0x0449, 0x044A, 0x044B, 0x044C, 0x044D, 0x044E, 0x044F,
    };
    std::string out;
    out.reserve( static_cast<size_t>( s.size() ) );
    for ( const QChar & ch : s ) {
        const uint16_t code = ch.unicode();
        if ( code < 0x80 ) {
            out.push_back( static_cast<char>( code ) );
            continue;
        }
        bool found = false;
        for ( int i = 0; i < 128 && !found; ++i ) {
            if ( table[i] == static_cast<wchar_t>( code ) ) {
                out.push_back( static_cast<char>( 0x80 + i ) );
                found = true;
            }
        }
        if ( !found )
            out.push_back( '?' );
    }
    return out;
}

